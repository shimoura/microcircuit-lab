"""
NEST backend.

This module contains the first implementation of the simulator backend.
"""

from __future__ import annotations

import logging
from collections.abc import Sequence
from pathlib import Path

import nest
import numpy as np
import pandas as pd

from microcircuit_lab.config.simulation import SimulationConfig
from microcircuit_lab.config.network import NetworkConfig
from microcircuit_lab.config.populations import PopulationConfig
from microcircuit_lab.config.stimuli import (
    DcStimulusConfig,
    InhomogeneousPoissonStimulusConfig,
    PoissonStimulusConfig,
)

logger = logging.getLogger(__name__)


class NestBackend:
    """
    Simple NEST backend.
    """

    def __init__(
        self,
        network: NetworkConfig,
        simulation_config: SimulationConfig,
        *,
        extension_modules: Sequence[str] = (),
    ) -> None:
        """
        extension_modules:
            Names of compiled NEST extension modules to load with
            nest.Install() before the network is built, e.g. a module
            generated by NESTML (pynestml.frontend.generate_nest_target)
            that defines the neuron model(s) this network's
            neurons.yaml references. Loaded fresh on every build(), since
            initialize() resets the kernel each time.
        """

        self._network = network
        self._simulation_config = simulation_config
        self._extension_modules = extension_modules
        self._recordings_dir: Path | None = None

        self.populations: dict[str, nest.NodeCollection] = {}
        self.background_generators: dict[str, nest.NodeCollection] = {}
        self.spike_recorder: nest.NodeCollection | None = None
        self.multimeter: nest.NodeCollection | None = None
        self.stimulus_generators: list[tuple] = []
        self._cached_spikes: tuple[np.ndarray, np.ndarray] | None = None

    def num_processes(self) -> int:
        return nest.NumProcesses()

    def rank(self) -> int:
        return nest.Rank()

    def sync_processes(self) -> None:
        nest.SyncProcesses()

    def prepare_output(self, run_dir: Path) -> None:
        """
        Point NEST's own ascii recording backend at ``run_dir/recordings``.

        NEST then writes spikes straight to disk during simulate() -- it
        never has to hold the full spike history in Python memory, and we
        never re-serialize what NEST already wrote. Must be called before
        build(); without it, the spike recorder falls back to NEST's in-memory
        mode (used transparently by get_spike_events/save_recordings).
        """

        self._recordings_dir = Path(run_dir) / "recordings"

    def initialize(self) -> None:
        """
        Initialize the NEST kernel.
        """

        nest.ResetKernel()

        for module in self._extension_modules:
            logger.info("Installing extension module %s", module)
            nest.Install(module)

        nest.set(
            resolution=self._simulation_config.resolution,
            local_num_threads=self._simulation_config.local_num_threads,
            rng_seed=self._simulation_config.rng_seed,
            print_time=self._simulation_config.print_time,
        )

        if self._recordings_dir is not None:
            self._recordings_dir.mkdir(parents=True, exist_ok=True)
            nest.set(
                data_path=str(self._recordings_dir),
                overwrite_files=True,
            )

    def build(self) -> None:
        """
        Build the complete network.
        """

        self.initialize()

        self.create_populations()

        if self._simulation_config.recording.spike_recording:
            self.create_spike_recorders()
            self.connect_spike_recorders()

        if self._simulation_config.recording.voltage_recording:
            self.create_multimeters()
            self.connect_multimeters()

        self.create_background_inputs()
        self.connect_background_inputs()

        if self._network.stimuli:
            self.create_stimuli()
            self.connect_stimuli()

        self.create_connections()

    def create_populations(self) -> None:
        """
        Create all neuron populations.
        """

        for pop_name, pop_cfg in self._network.populations.items():
            logger.info(
                "Creating %s (%d neurons)",
                pop_name,
                pop_cfg.size,
            )

            nodes = nest.Create(
                pop_cfg.neuron.model,
                pop_cfg.size,
            )

            self.initialize_population(nodes, pop_cfg)
            self.populations[pop_name] = nodes

    def initialize_population(
        self, nodes: nest.NodeCollection, pop_cfg: PopulationConfig
    ) -> None:
        """
        Initialize the parameters and state variables of a population.

        This includes neuron model parameters and the initial membrane
        potential distribution.
        """

        nodes.set(pop_cfg.neuron.parameters.model_dump())

        nodes.V_m = nest.random.normal(
            mean=pop_cfg.V0_mean,
            std=pop_cfg.V0_std,
        )

    def create_connections(self) -> None:
        """
        Connect populations according to the connectivity configuration.
        """

        logger.info("Creating recurrent connections:")

        for connection in self._network.connections:
            source = self.get_population(connection.source)
            target = self.get_population(connection.target)

            logger.info(
                "Connecting %s -> %s (N=%d, weight=%g, delay=%g)",
                connection.source,
                connection.target,
                connection.n_synapses,
                connection.weight.mean,
                connection.delay.mean,
            )

            nest.Connect(
                source,
                target,
                conn_spec={
                    "rule": "fixed_total_number",
                    "N": connection.n_synapses,
                },
                syn_spec={
                    "weight": self.create_weight_spec(connection.weight),
                    "delay": self.create_delay_parameter(connection.delay),
                },
            )

    def get_population(
        self,
        name: str,
    ) -> nest.NodeCollection:
        """
        Get the NEST node collection corresponding to a population name.
        """

        return self.populations[name]

    def create_spike_recorders(self) -> None:
        """
        Create one shared spike recorder for all populations.

        Records straight to ascii files under the directory set in
        prepare_output(), if any; otherwise keeps events in memory (NEST's
        default), matching the standalone-backend / no-output-requested case.
        """

        params = (
            {"record_to": "ascii", "label": "spikes"}
            if self._recordings_dir is not None
            else {}
        )
        self.spike_recorder = nest.Create("spike_recorder", params=params)

    def connect_spike_recorders(self) -> None:
        """
        Connect populations to the shared spike recorder.
        """

        for pop_name in self.populations:
            nest.Connect(
                self.get_population(pop_name),
                self.spike_recorder,
            )

    def create_multimeters(self) -> None:
        """
        Create one shared multimeter recording membrane potential.

        Records straight to ascii files under the directory set in
        prepare_output(), if any, same as spike recorders; otherwise
        keeps events in NEST's default in-memory mode.
        """

        params = {
            "record_from": ["V_m"],
            "interval": self._simulation_config.recording.voltage_interval,
        }
        if self._recordings_dir is not None:
            params.update({"record_to": "ascii", "label": "voltage"})

        self.multimeter = nest.Create("multimeter", params=params)

    def connect_multimeters(self) -> None:
        """
        Connect the shared multimeter to populations (with optional subsampling).
        """

        sample_size = self._simulation_config.recording.voltage_sample_size

        for pop_name in self.populations:
            nodes = self.get_population(pop_name)
            if sample_size is not None and sample_size < len(nodes):
                nodes = nodes[:sample_size]
            nest.Connect(
                self.multimeter,
                nodes,
            )

    def create_background_inputs(self) -> None:
        """
        Create one background Poisson generator per configured population.

        No-op when background_mode is "dc": the background drive was
        already injected as constant current onto each neuron's I_e by
        prepare_network, so no generator is created at all (see
        NetworkConfig.background_mode).
        """

        if self._network.background_mode == "dc":
            logger.info(
                "background_mode='dc': background drive is constant current "
                "(I_e), skipping Poisson generators."
            )
            return

        logger.info("Creating background Poisson generators:")

        for pop_name, input_cfg in self._network.background_inputs.items():
            logger.info(
                "Creating background Poisson input for %s (rate=%g Hz)",
                pop_name,
                input_cfg.rate,
            )
            pg = nest.Create(
                "poisson_generator",
                params={
                    "rate": input_cfg.rate,
                },
            )
            self.background_generators[pop_name] = pg

    def connect_background_inputs(self) -> None:
        """
        Connect background Poisson generators to populations.
        """

        for pop_name in self.background_generators:
            input_cfg = self._network.background_inputs[pop_name]
            nest.Connect(
                self.background_generators[pop_name],
                self.get_population(pop_name),
                syn_spec={
                    "weight": self.create_weight_spec(input_cfg.weight),
                    "delay": self.create_delay_parameter(input_cfg.delay),
                },
            )

    def create_stimuli(self) -> None:
        """
        Create one device per configured stimulus, dispatching on the
        stimulus's concrete type the same way create_weight_spec/
        create_delay_parameter dispatch on `distribution`. Each branch
        narrows to one StimulusConfig subtype, so only the fields that
        subtype actually declares are touched.
        """

        logger.info("Creating stimulus devices:")

        for stimulus in self._network.stimuli:
            logger.info(
                "Creating %s stimulus for %s (start=%g, stop=%s)",
                stimulus.type,
                stimulus.targets,
                stimulus.start,
                stimulus.stop,
            )

            params: dict = {"start": stimulus.start}
            if stimulus.stop is not None:
                params["stop"] = stimulus.stop

            if isinstance(stimulus, DcStimulusConfig):
                model = "dc_generator"
                params["amplitude"] = stimulus.amplitude
            elif isinstance(stimulus, PoissonStimulusConfig):
                model = "poisson_generator"
                params["rate"] = stimulus.rate
            elif isinstance(stimulus, InhomogeneousPoissonStimulusConfig):
                model = "inhomogeneous_poisson_generator"
                params["rate_times"] = stimulus.rate_times
                params["rate_values"] = stimulus.rate_values
            else:
                raise ValueError(f"Unsupported stimulus type: {type(stimulus).__name__!r}")

            device = nest.Create(model, params=params)
            self.stimulus_generators.append((stimulus, device))

    def connect_stimuli(self) -> None:
        """
        Connect each stimulus device to its target populations.

        `dc` devices are connected with the default synapse (weight 1.0
        per pA of amplitude); `poisson`/`inhomogeneous_poisson` devices
        use the configured weight/delay, same as background input.
        """

        for stimulus, device in self.stimulus_generators:
            syn_spec = None
            if not isinstance(stimulus, DcStimulusConfig):
                syn_spec = {
                    "weight": self.create_weight_spec(stimulus.weight),
                    "delay": self.create_delay_parameter(stimulus.delay),
                }

            for target in stimulus.targets:
                nest.Connect(device, self.get_population(target), syn_spec=syn_spec)

    def simulate(self) -> None:
        """
        Run the simulation, discarding any spike events cached from before it.
        """

        nest.Simulate(self._simulation_config.t_sim)
        self._cached_spikes = None

    def print_statistics(self) -> None:
        """
        Print simple statistics.
        """

        logger.info("")
        logger.info("Simulation statistics")
        logger.info("---------------------")

        if self.spike_recorder is None:
            return

        t_sim_s = self._simulation_config.t_sim / 1000.0

        for pop_name in self.populations:
            events = self.get_spike_events(pop_name)
            n_spikes = len(events["times"])
            n_neurons = self._network.populations[pop_name].size
            mean_rate = (n_spikes / (n_neurons * t_sim_s)) if (n_neurons and t_sim_s > 0) else 0.0

            logger.info(
                "%-6s  N=%5d  spikes=%7d  rate=%8.3f Hz",
                pop_name,
                n_neurons,
                n_spikes,
                mean_rate,
            )

    def create_weight_spec(self, weight):
        """
        Create a NEST weight parameter.

        A normal weight keeps the sign of its mean. A drawn value of the
        other sign is redrawn or clipped to 0, as set by the network's
        ``bound_mode``.
        """

        if weight.distribution == "fixed":
            return weight.mean

        std = abs(weight.mean * weight.rel_std)

        if weight.distribution == "normal":
            distribution = nest.random.normal(mean=weight.mean, std=std)
            clip = self._network.bound_mode == "clip"

            if weight.mean >= 0:
                if clip:
                    return nest.math.max(distribution, 0.0)
                return nest.math.redraw(distribution, min=0.0, max=float("inf"))

            if clip:
                return nest.math.min(distribution, 0.0)
            return nest.math.redraw(distribution, min=-float("inf"), max=0.0)

        if weight.distribution == "lognormal":
            variance = (weight.mean * weight.rel_std) ** 2
            sigma2 = np.log(1.0 + variance / weight.mean**2)
            sigma = np.sqrt(sigma2)
            mu = np.log(weight.mean) - sigma2 / 2.0

            return nest.random.lognormal(
                mean=mu,
                std=sigma,
            )

        raise NotImplementedError(f"Unsupported distribution: {weight.distribution}")

    def create_delay_parameter(self, delay):
        """
        Create a NEST delay parameter.

        A drawn delay below the minimum (``delay.minimum``, or half the
        simulation step if not set) is redrawn or clipped to the minimum,
        as set by the network's ``bound_mode``. The minimum is never below
        half the simulation step, which NEST would round to a delay of 0.
        A fixed delay is returned as given.
        """

        if delay.distribution == "fixed" or delay.rel_std == 0.0:
            return delay.mean

        std = delay.mean * delay.rel_std
        min_delay = 0.5 * nest.resolution
        if delay.minimum is not None:
            min_delay = max(delay.minimum, min_delay)

        if delay.distribution == "normal":
            distribution = nest.random.normal(
                mean=delay.mean,
                std=std,
            )

        elif delay.distribution == "lognormal":
            variance = std**2
            sigma_squared = np.log1p(variance / delay.mean**2)
            sigma = np.sqrt(sigma_squared)
            mu = np.log(delay.mean) - 0.5 * sigma_squared

            distribution = nest.random.lognormal(
                mean=mu,
                std=sigma,
            )

        else:
            raise ValueError(f"Unsupported delay distribution: {delay.distribution!r}")

        if self._network.bound_mode == "clip":
            return nest.math.max(distribution, min_delay)

        return nest.math.redraw(
            distribution,
            min=min_delay,
            max=float("inf"),
        )

    def _load_spikes(self) -> tuple[np.ndarray, np.ndarray]:
        """
        Load all spike events from disk (ascii mode) or NEST memory (memory mode),
        returning (sorted_senders, sorted_times) sorted by sender GID.
        Cached on self._cached_spikes.
        """
        if self._cached_spikes is not None:
            return self._cached_spikes

        if self.spike_recorder is None:
            self._cached_spikes = (np.array([], dtype=int), np.array([], dtype=float))
            return self._cached_spikes

        if self.spike_recorder.get("record_to") == "ascii":
            senders_list: list[np.ndarray] = []
            times_list: list[np.ndarray] = []

            for path in sorted(self._recordings_dir.glob("spikes-*.dat")):
                data = pd.read_csv(path, sep="\t", comment="#")
                senders_list.append(data["sender"].to_numpy())
                times_list.append(data["time_ms"].to_numpy())

            if not senders_list:
                senders = np.array([], dtype=int)
                times = np.array([], dtype=float)
            else:
                senders = np.concatenate(senders_list).astype(int)
                times = np.concatenate(times_list).astype(float)
        else:
            events = self.spike_recorder.get("events")
            senders = np.asarray(events["senders"], dtype=int)
            times = np.asarray(events["times"], dtype=float)

        if len(senders) > 0:
            order = np.argsort(senders, kind="stable")
            self._cached_spikes = (senders[order], times[order])
        else:
            self._cached_spikes = (np.array([], dtype=int), np.array([], dtype=float))

        return self._cached_spikes

    def get_spike_events(
        self,
        population: str,
    ) -> dict:
        """
        Return spike events for one population as {"senders": ..., "times": ...}.

        Filters the shared spike events by sender GID against this population's
        node collection.
        """
        sorted_senders, sorted_times = self._load_spikes()
        if len(sorted_senders) == 0:
            return {"senders": np.array([], dtype=int), "times": np.array([], dtype=float)}

        nodes = self.get_population(population)
        node_ids = nodes.tolist()
        min_gid = int(node_ids[0])
        max_gid = int(node_ids[-1])

        left = np.searchsorted(sorted_senders, min_gid, side="left")
        right = np.searchsorted(sorted_senders, max_gid + 1, side="left")

        return {
            "senders": sorted_senders[left:right],
            "times": sorted_times[left:right],
        }

    def save_recordings(self, run_dir: Path) -> list[Path]:
        """
        Return the spike (and, if enabled, voltage) recording files for
        this run.

        In ascii mode these were already written natively by NEST during
        simulate(); nothing is re-serialized. Spike recorders fall back to
        a CSV written here when in memory mode (no prepare_output() call);
        multimeters have no such fallback -- voltage traces are large
        enough that only the native ascii path is supported, so voltage
        data recorded in memory mode is simply not persisted.
        """

        run_dir = Path(run_dir)
        paths: list[Path] = []

        if self.spike_recorder is not None:
            if self.spike_recorder.get("record_to") == "ascii":
                paths.extend(sorted(self._recordings_dir.glob("spikes-*.dat")))
            else:
                paths.append(self._write_memory_recording_csv(run_dir))

        if self.multimeter is not None:
            if self.multimeter.get("record_to") == "ascii":
                paths.extend(sorted(self._recordings_dir.glob("voltage-*.dat")))

        return paths

    def _write_memory_recording_csv(self, run_dir: Path) -> Path:
        recordings_dir = run_dir / "recordings"
        recordings_dir.mkdir(parents=True, exist_ok=True)
        path = recordings_dir / "spikes.csv"

        if self.spike_recorder is None:
            np.savetxt(
                path,
                np.empty((0, 2)),
                delimiter=",",
                header="sender,time_ms",
                comments="",
                fmt=["%d", "%.3f"],
            )
            return path

        events = self.spike_recorder.get("events")
        senders = np.asarray(events["senders"], dtype=int)
        times = np.asarray(events["times"], dtype=float)
        order = np.argsort(times)

        np.savetxt(
            path,
            np.column_stack([senders[order], times[order]]),
            delimiter=",",
            header="sender,time_ms",
            comments="",
            fmt=["%d", "%.3f"],
        )
        return path
