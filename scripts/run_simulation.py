"""Run a generated network configuration, or re-plot an existing run,
with optional diagnostics.

Which diagnostics exist at all -- and their CLI flags -- come from
microcircuit_lab.analysis.PLOT_REGISTRY, not this script: adding a new
bundled diagnostic (microcircuit_lab.analysis.register_plot) makes it
show up here automatically, no changes needed in this file.
"""

import argparse
import logging

import matplotlib.pyplot as plt

from microcircuit_lab import Simulation
from microcircuit_lab.analysis import (
    PLOT_REGISTRY,
    check_reference_rates,
    check_unknown_plot_sections,
    list_areas,
)
from microcircuit_lab.config import AnalysisConfig
from microcircuit_lab.io.output import register_artifact


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run a generated network configuration, or re-plot an existing run."
    )
    parser.add_argument("--config-dir", default="configs")
    parser.add_argument(
        "--network", default=None, help="Network config directory name to simulate."
    )
    parser.add_argument(
        "--simulation",
        default=None,
        help="Simulation config name. Defaults to --network's value (see Simulation.from_yaml).",
    )
    parser.add_argument(
        "--run-dir",
        default=None,
        help="Re-plot an existing run directory instead of simulating (see "
        "Simulation.from_run_dir). Mutually exclusive with --network.",
    )
    parser.add_argument(
        "--extension-modules",
        nargs="+",
        default=None,
        help="Compiled NEST extension module name(s) to load with nest.Install() "
        "before the network is built, e.g. a module generated by NESTML that "
        "defines a neuron model this network's neurons.yaml references. Forwarded "
        "to NestBackend via Simulation.from_yaml's backend_options.",
    )
    parser.add_argument(
        "--analysis",
        default=None,
        help="Analysis config name (configs/analysis/<name>.yaml). Defaults to the "
        "network name. If no such file exists, built-in defaults are used.",
    )
    parser.add_argument(
        "--begin", type=float, default=None, help="Analysis start time in ms. Overrides YAML."
    )
    parser.add_argument(
        "--end", type=float, default=None, help="Analysis end time in ms. Overrides YAML."
    )
    parser.add_argument(
        "--area",
        default=None,
        help="Area to plot for multi-area networks, or 'all' for one set of plots per "
        "area (plots/<area>/). Overrides YAML.",
    )
    parser.add_argument(
        "--reference",
        action=argparse.BooleanOptionalAction,
        default=None,
        help="Show reference firing rates. Overrides YAML.",
    )
    for name in PLOT_REGISTRY:
        flag = name.replace("_", "-")
        parser.add_argument(
            f"--{flag}", action=argparse.BooleanOptionalAction, default=None,
            help=f"Enable/disable the {name} plot. Overrides YAML.",
        )
    parser.add_argument(
        "--validate-reference",
        action="store_true",
        help="Check simulated rates against reference.full_mean_rates and print pass/fail "
        "(non-fatal; does not affect exit code). No-op if the network has no reference.",
    )
    parser.add_argument(
        "--reference-rtol",
        type=float,
        default=0.5,
        help="Relative tolerance for --validate-reference.",
    )
    parser.add_argument(
        "--show",
        action="store_true",
        help="Open plot windows interactively (plots are always saved to output_dir regardless).",
    )

    args = parser.parse_args()
    if bool(args.network) == bool(args.run_dir):
        parser.error("Pass exactly one of --network or --run-dir.")
    return args


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")

    args = _parse_args()

    if args.run_dir is not None:
        simulation = Simulation.from_run_dir(args.run_dir)
        network_name = simulation.network_name
    else:
        backend_options = (
            {"extension_modules": args.extension_modules}
            if args.extension_modules
            else None
        )
        simulation = Simulation.from_yaml(
            config_dir=args.config_dir,
            network_name=args.network,
            simulation_name=args.simulation,
            backend_options=backend_options,
        )
        simulation.run()
        network_name = args.network

    analysis_config = AnalysisConfig.from_yaml(
        config_dir=args.config_dir,
        network_name=network_name,
        analysis_name=args.analysis,
    )
    check_unknown_plot_sections(analysis_config)

    begin = args.begin if args.begin is not None else analysis_config.begin
    end = args.end if args.end is not None else analysis_config.end
    area = args.area if args.area is not None else analysis_config.area
    show_reference = (
        args.reference if args.reference is not None else analysis_config.show_reference
    )

    print(f"Run directory: {simulation.output_dir}")

    if area == "all":
        areas = list_areas(simulation)
        if not areas:
            raise SystemExit("--area all needs a multi-area network (<area>__<population> names).")
        plot_targets = [(a, simulation.output_dir / "plots" / a) for a in areas]
        area = None
    else:
        plot_targets = [(area, simulation.output_dir / "plots")]

    for name, spec in PLOT_REGISTRY.items():
        plot_config = analysis_config.plot_config(name, spec.config_cls)
        cli_override = getattr(args, name)
        enabled = cli_override if cli_override is not None else plot_config.enabled
        if not enabled:
            continue

        for plot_area, plots_dir in plot_targets:
            save_path = plots_dir / spec.filename
            kwargs = dict(
                begin=begin, end=end, area=plot_area, style=analysis_config.style,
                config=plot_config, save_path=save_path, show=args.show,
            )
            if name == "firing_rates":
                kwargs["show_reference"] = show_reference
            spec.plot_fn(simulation, **kwargs)
            register_artifact(simulation.output_dir, "plots", save_path)
            if not args.show:
                plt.close("all")

    print(f"Plots saved under: {simulation.output_dir / 'plots'}")
    print(
        "Re-plot without re-simulating: "
        f"python scripts/run_simulation.py --run-dir {simulation.output_dir}"
    )

    if args.validate_reference:
        try:
            deviations = check_reference_rates(
                simulation, begin=begin, end=end, area=area,
                rtol=args.reference_rtol,
            )
            print(f"\nReference check passed (rtol={args.reference_rtol:.0%}):")
            for name, dev in deviations.items():
                print(f"  {name:>12}  {dev:+.1%}")
        except ValueError:
            print("\nNo reference.full_mean_rates on this network -- skipping --validate-reference.")
        except AssertionError as exc:
            print(f"\nReference check FAILED: {exc}")


if __name__ == "__main__":
    main()
